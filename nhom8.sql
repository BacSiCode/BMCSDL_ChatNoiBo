CREATE OR REPLACE PACKAGE BODY PKG_SECURITY AS
    v_key RAW(32) := UTL_RAW.CAST_TO_RAW('KhoaBiMat_Nhom8_1234567890123456'); 
    FUNCTION Encrypt_AES(p_input IN VARCHAR2) RETURN VARCHAR2 IS
        v_encrypted RAW(2000);
    BEGIN
        IF p_input IS NULL THEN RETURN NULL; END IF;
        v_encrypted := DBMS_CRYPTO.ENCRYPT(
            src => UTL_RAW.CAST_TO_RAW(p_input),
            typ => DBMS_CRYPTO.ENCRYPT_AES256 + DBMS_CRYPTO.CHAIN_CBC + DBMS_CRYPTO.PAD_PKCS5,
            key => v_key
        );
        RETURN RAWTOHEX(v_encrypted);
    END;

    FUNCTION Decrypt_AES(p_input IN VARCHAR2) RETURN VARCHAR2 IS
        v_decrypted RAW(2000);
    BEGIN
        IF p_input IS NULL THEN RETURN NULL; END IF;
        v_decrypted := DBMS_CRYPTO.DECRYPT(
            src => HEXTORAW(p_input),
            typ => DBMS_CRYPTO.ENCRYPT_AES256 + DBMS_CRYPTO.CHAIN_CBC + DBMS_CRYPTO.PAD_PKCS5,
            key => v_key
        );
        RETURN UTL_RAW.CAST_TO_VARCHAR2(v_decrypted);
    EXCEPTION WHEN OTHERS THEN RETURN NULL; END;
END;
/

