CREATE OR REPLACE PACKAGE PKG_LOG_SECURITY AS
    PROCEDURE INSERT_LOG_HYBRID(p_userid IN VARCHAR2, p_ip IN VARCHAR2);   
    -- Hàm giải mã lấy lại IP gốc
    FUNCTION DECRYPT_IP_HYBRID(p_ip_enc IN RAW, p_key_enc IN RAW) RETURN VARCHAR2;
END;
/

CREATE OR REPLACE PACKAGE BODY PKG_LOG_SECURITY AS
    FUNCTION GEN_SESSION_KEY RETURN RAW IS
    BEGIN
        RETURN DBMS_CRYPTO.RANDOMBYTES(32);
    END;


    PROCEDURE INSERT_LOG_HYBRID(p_userid IN VARCHAR2, p_ip IN VARCHAR2) IS
        v_session_key RAW(32);
        v_ip_enc      RAW(2000);
        v_key_enc     RAW(2000);
    BEGIN
        v_session_key := GEN_SESSION_KEY();
       
        v_ip_enc := DBMS_CRYPTO.ENCRYPT(
            src => UTL_RAW.CAST_TO_RAW(p_ip),
            typ => DBMS_CRYPTO.ENCRYPT_AES256 + DBMS_CRYPTO.CHAIN_CBC + DBMS_CRYPTO.PAD_PKCS5,
            key => v_session_key
        );
        v_key_enc := HEXTORAW(PKG_SECURITY.Encrypt_AES(RAWTOHEX(v_session_key)));

        INSERT INTO LOGIN_HISTORY (USERID, LOGIN_TIME, IP_ENCRYPTED, SESSION_KEY_ENC)
        VALUES (p_userid, CURRENT_TIMESTAMP, v_ip_enc, v_key_enc);
        
    EXCEPTION WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20001, 'Loi Hybrid Encrypt: ' || SQLERRM);
    END;

    -- Hàm giải mã IP
    FUNCTION DECRYPT_IP_HYBRID(p_ip_enc IN RAW, p_key_enc IN RAW) RETURN VARCHAR2 IS
        v_session_key RAW(32);
        v_ip_decrypted RAW(2000);
    BEGIN
        IF p_ip_enc IS NULL OR p_key_enc IS NULL THEN RETURN NULL; END IF;
        v_session_key := HEXTORAW(PKG_SECURITY.Decrypt_AES(RAWTOHEX(p_key_enc)));
        v_ip_decrypted := DBMS_CRYPTO.DECRYPT(
            src => p_ip_enc,
            typ => DBMS_CRYPTO.ENCRYPT_AES256 + DBMS_CRYPTO.CHAIN_CBC + DBMS_CRYPTO.PAD_PKCS5,
            key => v_session_key
        );
        
        RETURN UTL_RAW.CAST_TO_VARCHAR2(v_ip_decrypted);
    EXCEPTION WHEN OTHERS THEN
        RETURN 'Error-Decrypt';
    END;

END;
/
COMMIT;

